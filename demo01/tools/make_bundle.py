#!/usr/bin/env python3
"""
Generate guardian_bundle.py — a single self-extracting text file that
contains the complete Guardian demo01 source tree.

Purpose:

Some execution environments (for example, a Glean agent's sandboxed
code interpreter) cannot reach GitHub, so `git clone` fails. The bundle
lets an operator upload ONE plain-text file; running it recreates the
full project so the runbook Section 0 Compile Protocol can proceed.

Usage (from the demo01 directory):

    python3 tools/make_bundle.py

Output:

    guardian_bundle.py   (commit it, or hand it to the operator)

Extraction (in the target environment):

    python3 guardian_bundle.py [target-directory]

Default target directory: ./guardian

The bundle format is plain text: each file is delimited by sentinel
lines, so the bundle is reviewable before execution. Binary files are
not supported and are intentionally excluded.
"""

from __future__ import annotations

import sys
from pathlib import Path

FILE_SENTINEL = "#<<<GUARDIAN_BUNDLE_FILE>>>"
END_SENTINEL = "#<<<GUARDIAN_BUNDLE_END>>>"

INCLUDE_GLOBS = [
    "*.py",
    "*.md",
    "requirements.txt",
    "baseline/*.json",
    "registry/*.json",
    "mock_telemetry/*.json",
    ".gitignore",
]

EXCLUDE_NAMES = {
    "guardian_bundle.py",
}

EXTRACTOR_HEADER = '''#!/usr/bin/env python3
"""
Guardian Telemetry Swarm — self-extracting source bundle.

This single text file contains the complete Guardian demo01 project.

Extract:

    python3 guardian_bundle.py [target-directory]

Default target directory: ./guardian

Then follow Section 0 (Compile Protocol) of the extracted runbook.md
from inside the target directory.

Generated by tools/make_bundle.py. Do not edit by hand; regenerate
instead.
"""

import sys
from pathlib import Path

FILE_SENTINEL = {file_sentinel!r}
END_SENTINEL = {end_sentinel!r}


def main() -> int:
    target = Path(sys.argv[1] if len(sys.argv) > 1 else "guardian")

    source = Path(__file__).read_text(encoding="utf-8").splitlines(
        keepends=True
    )

    written = 0
    current_path = None
    current_lines = []

    for line in source:
        stripped = line.rstrip("\\n")

        if stripped.startswith(FILE_SENTINEL):
            current_path = stripped[len(FILE_SENTINEL):].strip()
            current_lines = []

        elif stripped == END_SENTINEL and current_path is not None:
            destination = target / current_path

            if not destination.resolve().is_relative_to(
                target.resolve()
            ):
                raise ValueError(
                    f"Refusing path outside target: {{current_path}}"
                )

            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(
                "".join(current_lines), encoding="utf-8"
            )
            print(f"wrote {{destination}}")
            written += 1
            current_path = None

        elif current_path is not None:
            # Data lines are stored with a leading "#" so the bundle
            # stays a syntactically valid Python file.
            if line.startswith("#"):
                current_lines.append(line[1:])

    if written == 0:
        print("ERROR: no files found in bundle", file=sys.stderr)
        return 1

    print()
    print(f"Extracted {{written}} files to {{target.resolve()}}")
    print("Next: cd into the directory and follow runbook.md Section 0.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


# ============================================================
# BUNDLED FILES FOLLOW. Everything below is data, not code.
# ============================================================

'''


def collect_files(root: Path) -> list[Path]:
    files: set[Path] = set()

    for pattern in INCLUDE_GLOBS:
        for path in root.glob(pattern):
            if path.is_file() and path.name not in EXCLUDE_NAMES:
                files.add(path)

    return sorted(files)


def main() -> int:
    root = Path(__file__).resolve().parent.parent

    files = collect_files(root)

    if not files:
        print("ERROR: no files collected", file=sys.stderr)
        return 1

    parts = [
        EXTRACTOR_HEADER.format(
            file_sentinel=FILE_SENTINEL,
            end_sentinel=END_SENTINEL,
        )
    ]

    for path in files:
        relative = path.relative_to(root).as_posix()
        content = path.read_text(encoding="utf-8")

        if "<<<GUARDIAN_BUNDLE" in content:
            print(
                f"ERROR: {relative} contains a bundle sentinel",
                file=sys.stderr,
            )
            return 1

        if not content.endswith("\n"):
            content += "\n"

        # Store every data line behind a "#" so the whole bundle remains
        # a valid Python source file (Python parses the entire file,
        # including everything after the extractor).
        commented = "".join(
            "#" + line
            for line in content.splitlines(keepends=True)
        )

        parts.append(f"{FILE_SENTINEL} {relative}\n")
        parts.append(commented)
        parts.append(f"{END_SENTINEL}\n\n")

    output = root / "guardian_bundle.py"
    output.write_text("".join(parts), encoding="utf-8")

    size_kb = output.stat().st_size / 1024

    print(f"Bundled {len(files)} files into {output} ({size_kb:.0f} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
